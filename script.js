function renderPackages(filter = "tutti") {

  let filtered = packages;

  if (filter === "settembre") {
    filtered = packages.filter(p => p.month === "settembre");
  }

  if (filter === "ottobre") {
    filtered = packages.filter(p => p.month === "ottobre");
  }

  if (filter === "accessibile") {
    filtered = packages.filter(p => p.accessible);
  }

  packagesGrid.innerHTML =
    filtered.map(createPackageCard).join("");
}


